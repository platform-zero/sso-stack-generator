"""Pure Quadlet rendering. Rendering is neither installation nor readiness proof."""
from __future__ import annotations

import ipaddress
from pathlib import PurePosixPath

from .model import Catalog, ContractError, fields, identifier, text


def quote(value: str) -> str:
    # systemd performs % expansion even inside quotes. Reject '$' where some
    # directives/Podman versions can perform variable substitution.
    value = text(value)
    if "$" in value:
        raise ContractError("variable expansion forbidden in unit value")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'


def _absolute(value):
    value = text(value)
    path = PurePosixPath(value)
    if (not path.is_absolute() or ".." in path.parts or path == PurePosixPath("/")
            or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789/._-' for c in value)):
        raise ContractError("unsafe container destination")
    return value


def probe_spec(service):
    probes = service.declaration.get("probes", [])
    if not isinstance(probes, list):
        raise ContractError("probes must be an array")
    for probe in probes:
        fields(probe, {"kind", "host", "port"}, {"path", "status", "timeoutSeconds"})
        if probe["kind"] not in ("tcp", "http"):
            raise ContractError("unsupported readiness probe")
        host = text(probe["host"])
        # Specs are host-side observations; DNS and private IPs are supported.
        if any(c in host for c in "/@?#: "):
            raise ContractError("invalid readiness host")
        if type(probe["port"]) is not int or not 1 <= probe["port"] <= 65535:
            raise ContractError("invalid readiness port")
        timeout = probe.get("timeoutSeconds", 30)
        if type(timeout) is not int or not 1 <= timeout <= 300:
            raise ContractError("invalid readiness deadline")
        if probe["kind"] == "http":
            path = probe.get("path", "/")
            if not isinstance(path, str) or not path.startswith("/") or path.startswith("//") or any(ord(c) < 33 for c in path):
                raise ContractError("invalid readiness path")
            if type(probe.get("status", 200)) is not int or not 100 <= probe.get("status", 200) <= 599:
                raise ContractError("invalid readiness status")
    return {"schemaVersion": 1, "service": service.id, "probes": probes}


def render(catalog: Catalog, targets: list[str]) -> tuple[dict, dict[str, str]]:
    plan = catalog.plan(targets)
    result = {}
    for name in plan["services"]:
        service = catalog.services[name]
        declaration = service.declaration
        if not service.image:
            raise ContractError("build requires pinned image for every selected service")
        spec = probe_spec(service)
        lifecycle = declaration.get("lifecycle", "daemon")
        if lifecycle not in ("daemon", "oneshot"):
            raise ContractError("invalid service lifecycle")
        lines = ["# Generated by p0; do not edit.", "[Unit]", f"Description=P0 {name}"]
        for edge in service.requires:
            provider = catalog.services[edge.service]
            if edge.kind == "ready" and not probe_spec(provider)["probes"]:
                raise ContractError("readiness dependency lacks provider probes")
            if edge.kind != "integration" and provider.runtime == service.runtime:
                lines += [f"After=p0-{edge.service}.service"]
            # Readiness is handled by an operation probe, not forged with After=.
        lines += ["", "[Container]", f"Image={service.image}",
                  f"ContainerName=p0-{name}", "NoNewPrivileges=true"]
        lines += ["Pull=never", "Label=io.platform-zero.managed=v2", f"Label=io.platform-zero.service={name}"]
        environment = declaration.get("environment", {})
        if not isinstance(environment, dict):
            raise ContractError("environment must be an object")
        import re
        for key, value in sorted(environment.items()):
            if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", key):
                raise ContractError("invalid environment key")
            if re.search(r"PASSWORD|TOKEN|SECRET|PRIVATE_KEY", key) and not key.endswith("_FILE"):
                raise ContractError("secret values must use file references")
            lines.append("Environment=" + quote(key + "=" + text(value)))
        entrypoint = declaration.get("entrypoint")
        if entrypoint is not None:
            # A single executable only; additional args belong in command.
            lines.append("Entrypoint=" + _absolute(entrypoint))
        networks = declaration.get("networks", [])
        if not isinstance(networks, list):
            raise ContractError("networks must be unique identifiers")
        for network in networks:
            identifier(network)
        if len(set(networks)) != len(networks):
            raise ContractError("networks must be unique identifiers")
        if not networks:
            lines.append("Network=none")
        else:
            lines.append(f"NetworkAlias={name}")
        for network in networks:
            identifier(network)
            filename = f"p0-network-{network}"
            result[f"quadlet/{service.runtime}/{filename}.network"] = (
                "# Generated by p0; do not edit.\n[Network]\n"
                f"NetworkName=p0-{network}\nLabel=io.platform-zero.managed=v2\n")
            lines.append(f"Network={filename}.network")
        mounts = declaration.get("mounts", [])
        if not isinstance(mounts, list):
            raise ContractError("mounts must be an array")
        destinations = set()
        for mount in mounts:
            fields(mount, {"kind", "source", "target"}, {"readOnly", "sha256"})
            source = identifier(mount["source"])
            target = _absolute(mount["target"])
            if target in destinations:
                raise ContractError("duplicate mount destination")
            destinations.add(target)
            readonly = mount.get("readOnly", mount["kind"] != "volume")
            if type(readonly) is not bool:
                raise ContractError("readOnly must be boolean")
            if 'sha256' in mount and mount['kind'] != 'config':
                raise ContractError('byte binding only applies to configuration mounts')
            if mount["kind"] == "volume":
                volume = 'p0-' + source
                result[f"quadlet/{service.runtime}/{volume}.volume"] = (
                    "# Generated by p0; do not edit.\n[Volume]\n"
                    f"VolumeName={volume}\nLabel=io.platform-zero.managed=v2\n")
                lines.append("Volume=" + volume + '.volume:' + target + (':ro' if readonly else ''))
            elif mount["kind"] == "secret" and readonly:
                lines.append("Secret=p0-" + source + ',type=mount,target=' + target)
            elif mount["kind"] == "config" and readonly:
                checksum = mount.get('sha256')
                if not isinstance(checksum, str) or not re.fullmatch('[a-f0-9]{64}', checksum):
                    raise ContractError('configuration mount needs explicit byte identity')
                lines.append("Volume=/etc/p0-v2/config/" + checksum + ':' + target + ':ro')
            else:
                raise ContractError("unsupported mount type or writable configuration")
        endpoints = declaration.get("endpoints", [])
        if not isinstance(endpoints, list):
            raise ContractError("endpoints must be an array")
        for endpoint in endpoints:
            fields(endpoint, {"port", "hostPort", "bind"}, {"protocol", "public"})
            for key in ("port", "hostPort"):
                if type(endpoint[key]) is not int or not 1 <= endpoint[key] <= 65535:
                    raise ContractError("invalid endpoint port")
            try:
                address = ipaddress.ip_address(endpoint["bind"])
            except (ValueError, TypeError) as error:
                raise ContractError("endpoint bind must be an IP address") from error
            public = endpoint.get("public", False)
            if type(public) is not bool or (public and service.runtime != "rootful"):
                raise ContractError("public ports require explicitly rootful edge")
            if not public and (address.is_unspecified or not (address.is_private or address.is_loopback)):
                raise ContractError("upstream port must bind a private address")
            protocol = endpoint.get("protocol", "tcp")
            if protocol not in ("tcp", "udp"):
                raise ContractError("invalid endpoint protocol")
            bind = f"[{address}]" if address.version == 6 else str(address)
            lines.append(f"PublishPort={bind}:{endpoint['hostPort']}:{endpoint['port']}/{protocol}")
        command = declaration.get("command", [])
        if not isinstance(command, list) or any(not isinstance(v, str) for v in command):
            raise ContractError("command must be string arguments")
        if command:
            lines.append("Exec=" + " ".join(quote(arg) for arg in command))
        resources = declaration.get("resources", {})
        fields(resources, set(), {"memoryMax", "tasksMax"})
        lines += ["", "[Service]", "TimeoutStartSec=300", "TimeoutStopSec=90"]
        if lifecycle == "oneshot":
            lines += ["Type=oneshot", "RemainAfterExit=yes", "Restart=no"]
        elif service.runtime != "test":
            lines.append("Restart=on-failure")
        for key, directive in (("memoryMax", "MemoryMax"), ("tasksMax", "TasksMax")):
            if key in resources:
                if type(resources[key]) is not int or resources[key] < 1:
                    raise ContractError("resource limits must be positive integers")
                lines.append(f"{directive}={resources[key]}")
        # No auto-start at boot merely from rendering/installing. Activation is
        # explicit and separate from desired-state publication.
        result[f"quadlet/{service.runtime}/p0-{name}.container"] = "\n".join(lines) + "\n"
        if spec["probes"]:
            from .model import canonical
            result[f"readiness/{name}.json"] = canonical(spec).decode() + "\n"
    # Validate mount/probe/endpoint contracts on all selected inputs above.
    return plan, result
